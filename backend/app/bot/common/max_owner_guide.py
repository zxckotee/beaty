def max_onboarding_guide_short() -> str:
    return MAX_GUIDE_SHORT


def max_onboarding_guide_parts() -> list[str]:
    parts = _max_guide_full_parts()
    for part in parts:
        if len(part) > TELEGRAM_MESSAGE_LIMIT:
            raise ValueError(f"guide part too long ({len(part)} chars)")
    return parts


def platform_bot_help_text() -> str:
    return """Команды бота Beaty для владельцев салона

/start — подключить салон или обновить токен
/status — статистика платформы (служебно)
/maxhelp — пошагово: свой MAX-бот и кабинет MAX
/maxquick — краткая шпаргалка по MAX
/help — этот список

Telegram-бот салона — токен из @BotFather.
MAX — сначала создайте бота в MAX для партнёров; подробно: /maxhelp"""


def max_owner_guide_tail() -> str:
    return "\n\nДальше в кабинете MAX: Чат-боты → Настройки → ссылка мини-приложения (см. /maxhelp)."


async def send_max_onboarding_full(message: Message) -> None:
    for part in max_onboarding_guide_parts():
        await message.answer(part)


async def send_max_onboarding_short(message: Message) -> None:
    await message.answer(max_onboarding_guide_short())