def docs_sections(*, audience: Audience | None = None) -> list[dict[str, Any]]:
    rows = _sections()
    if audience is None:
        return rows
    if audience == "manager":
        return [s for s in rows if s["audience"] in {"client", "manager"}]
    return [s for s in rows if s["audience"] == audience]


