def get_legal_document(slug: str) -> LegalDocument | None:
    return _REGISTRY.get(slug)


def related_legal_links(slug: str) -> list[dict[str, str]]:
    return [{"href": href, "label": label} for href, label in _RELATED.get(slug, [])]


def legal_document_as_dict(doc: LegalDocument) -> dict[str, Any]:
    return {
        "slug": doc.slug,
        "title": doc.title,
        "intro": doc.intro,
        "effective_date": doc.effective_date,
        "sections": [
            {
                "title": s.title,
                "paragraphs": s.paragraphs,
                "bullets": s.bullets,
                "ordered": s.ordered,
            }
            for s in doc.sections
        ],
    }